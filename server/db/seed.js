async function seedDatabase(productsDB) {
  const count = await productsDB.countAsync({});
  if (count > 0) {
    console.log(`✅ Database already seeded with ${count} products.`);
    return;
  }
  console.log('🌱 Seeding database with NMNORA products...');
  for (const product of products) {
    await productsDB.insertAsync(product);
  }
  console.log(`✅ Seeded ${products.length} products successfully!`);
}

